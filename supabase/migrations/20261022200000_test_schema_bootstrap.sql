
-- TEMPORARY LOCAL TEST SCHEMA
-- Do not use this as a production migration.

CREATE TABLE public.patients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_code text,
    full_name text,
    date_of_birth date,
    sex text,
    contact_number text,
    email text,
    address text,
    allergies text,
    medical_history text,
    blood_group text,
    last_visit date,
    status text,
    created_at timestamptz DEFAULT now()
);

CREATE TABLE public.staff (
    staff_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id uuid,
    full_name text,
    specialization text,
    role text,
    status text,
    created_at timestamptz DEFAULT now()
);

CREATE TABLE public.appointments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id bigint REFERENCES public.patients(id),
    staff_id bigint REFERENCES public.staff(staff_id),
    service_type text,
    appointment_date date,
    start_time time,
    end_time time,
    notes text,
    status text,
    created_at timestamptz DEFAULT now()
);

CREATE TABLE public.activity_logs (
    log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id uuid,
    action text,
    description text,
    created_at timestamptz DEFAULT now()
);

-- Enable RLS for local policy testing.
ALTER TABLE public.patients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.staff ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.activity_logs ENABLE ROW LEVEL SECURITY;

-- Allow authenticated test requests to reach RLS policies.
GRANT SELECT, INSERT, UPDATE, DELETE
ON public.patients, public.staff,
   public.appointments, public.activity_logs
TO authenticated;

GRANT USAGE, SELECT
ON ALL SEQUENCES IN SCHEMA public
TO authenticated;
